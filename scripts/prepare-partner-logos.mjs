/**
 * Prepares the partner logos from assets/img/loga_partneri into
 * public/brand/partners.
 *
 * Three of the four supplied SVGs are ordinary white marks and are copied
 * straight through. The Equity Solutions file is a NEGATIVE: a white square
 * with the wordmark knocked out of it, so rendered as-is it is a white tile,
 * and next to three transparent marks at 20px in the hero it would read as a
 * blob with unreadable micro-type.
 *
 * The inversion is exact and needs no redrawing. The positive artwork is
 *
 *     (the square) minus (the negative's own shapes)
 *
 * which is what an SVG luminance mask expresses directly: paint the whole
 * square white in the mask, paint every shape of the original black, and
 * what stays visible is the letterforms - counters included, because the
 * white islands sitting inside the letters in the negative are shapes too
 * and mask out the same way.
 *
 * The new viewBox crops to the wordmark's own bounding box (measured from the
 * rendered alpha channel: 67,238 327x157 inside the 433x434 original), so the
 * mark sizes like the other three instead of carrying half a square of
 * padding.
 *
 * Run from the repo root:
 *   node scripts/prepare-partner-logos.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const SRC = "assets/img/loga_partneri";
const OUT = "public/brand/partners";

/** Source file -> output slug. `invert` carries the crop of the wordmark. */
const JOBS = [
  { source: "audit.svg", name: "audit-one" },
  { source: "avant.svg", name: "avant" },
  { source: "sporitelna.svg", name: "ceska-sporitelna" },
  {
    source: "equity.svg",
    name: "equity-solutions",
    invert: { canvas: [433, 434], crop: [67, 238, 327, 157] },
  },
];

mkdirSync(OUT, { recursive: true });

for (const job of JOBS) {
  const svg = readFileSync(join(SRC, job.source), "utf8");

  if (!job.invert) {
    writeFileSync(join(OUT, `${job.name}.svg`), svg);
    console.log(`${job.source} -> ${job.name}.svg (copied)`);
    continue;
  }

  // Every drawn shape of the negative, in document order.
  const shapes = svg.match(/<(?:path|polygon|polyline|rect|circle|ellipse)\b[^>]*\/?>/g) ?? [];
  if (shapes.length === 0) throw new Error(`no shapes found in ${job.source}`);

  const [cw, ch] = job.invert.canvas;
  const [x, y, w, h] = job.invert.crop;
  const masked = shapes
    .map((s) => s.replace(/\sclass="[^"]*"/, "").replace(/\sfill="[^"]*"/, "").replace(/\/?>$/, ' fill="#000"/>'))
    .join("\n      ");

  const out = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${w} ${h}">
  <!-- Generated by scripts/prepare-partner-logos.mjs from ${job.source}, which is
       a negative (white tile, wordmark knocked out). The mask turns it positive. -->
  <mask id="mark" maskUnits="userSpaceOnUse" x="0" y="0" width="${cw}" height="${ch}">
    <rect x="0" y="0" width="${cw}" height="${ch}" fill="#fff"/>
    ${masked}
  </mask>
  <rect x="0" y="0" width="${cw}" height="${ch}" fill="#fff" mask="url(#mark)"/>
</svg>
`;
  writeFileSync(join(OUT, `${job.name}.svg`), out);
  console.log(`${job.source} -> ${job.name}.svg (inverted, ${shapes.length} shapes, cropped to ${w}x${h})`);
}
